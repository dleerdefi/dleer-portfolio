#!/usr/bin/env python3
"""Subsets JetBrains Mono for the site (docs/PORTFOLIO_V2_SPEC.md, phase 1, P3).

The full fonts are about 92 KB each. The subsets keep Latin, the punctuation, arrows, box drawing,
block and geometric shapes the site draws with. The script writes app/styles/03-fonts.css: each
subset's unicode-range is exactly its glyphs, and each full font's is exactly the glyphs it has
beyond the subset. So a character in neither (an emoji, a symbol JetBrains Mono lacks) never makes
the browser download a full font to find out, and a rare one it does have downloads it only on
pages that use it.

Regular keeps every OpenType feature (code ligatures included: body text and code blocks use it);
Bold keeps kerning only, since headings and labels never show ligatures.

  pip install fonttools brotli
  python3 scripts/subset-fonts.py
"""
from pathlib import Path
import subprocess
from fontTools.ttLib import TTFont

UNICODES = (
    "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+0394,U+2013-2014,U+2018-201A,"
    "U+201C-201E,U+2020-2022,U+2026,U+2030,U+2039-203A,U+2044,U+20AC,U+2122,U+2190-2193,U+2196-2199,U+2212,"
    "U+2248,U+2260,U+2264-2265,U+2500-259F,U+25A0-25FF,U+2713,U+2715,U+2717,U+276F"
)
WEIGHTS = {"Regular": [], "Bold": ["--layout-features=kern"]}


def ranges(codepoints):
    cps = sorted(codepoints)
    out, start, prev = [], cps[0], cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        out.append(f"U+{start:04X}" if start == prev else f"U+{start:04X}-{prev:04X}")
        if cp is not None:
            start = prev = cp
    return ", ".join(out)


faces = []
for weight, extra in WEIGHTS.items():
    css_weight = 400 if weight == "Regular" else 700
    full = f"public/fonts/JetBrainsMono-{weight}.woff2"
    subset = f"public/fonts/JetBrainsMono-{weight}.subset.woff2"
    subprocess.run(["pyftsubset", full, f"--unicodes={UNICODES}", "--flavor=woff2", f"--output-file={subset}", *extra], check=True)
    kept = set(TTFont(subset).getBestCmap())
    rest = set(TTFont(full).getBestCmap()) - kept
    print(f"{subset}: {len(kept)} characters, {Path(subset).stat().st_size / 1024:.1f} KB; full font adds {len(rest)}")
    faces.append((css_weight, full, rest))
    faces.append((css_weight, subset, kept))

# Full faces first: for overlapping ranges browsers check the last-defined face first, and the
# ranges do not overlap anyway. Only the Regular subset is preloaded (app/layout.tsx).
blocks = []
for css_weight, path, cps in faces:
    blocks.append(f"""@font-face {{
  font-family: "JetBrains Mono";
  src: url("/{path.removeprefix('public/')}") format("woff2");
  font-weight: {css_weight};
  font-style: normal;
  font-display: swap;
  unicode-range: {ranges(cps)};
}}""")
Path("app/styles/03-fonts.css").write_text(
    "/* JetBrains Mono. Generated by scripts/subset-fonts.py; rerun it instead of editing.        */\n"
    "/* The .subset files cover what the site draws with and are what pages download; the full   */\n"
    "/* files cover only the glyphs beyond them, so they load only on a page that uses one.      */\n\n"
    + "\n\n".join(blocks) + "\n"
)
print("wrote app/styles/03-fonts.css")
