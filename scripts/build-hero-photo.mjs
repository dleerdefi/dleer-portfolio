// Crops and sizes the profile photo for the desktop neofetch tile, where it replaces the ASCII logo
// (components/home/HeroPhoto.tsx). The originals are 1536 x 2048 and 0.5 to 0.9 MB; the tile shows
// the photo 150 to 260 CSS px wide, so this writes 3:4 copies at 260, 390 and 520 px (1x, 1.5x and
// 2x), for the plain photo and its RF-DETR detection version, cropped identically so the boxes
// line up when the tile switches between them. Run it after changing the photo, then commit the
// outputs:
//
//   node scripts/build-hero-photo.mjs          # the whole photo
//   node scripts/build-hero-photo.mjs upper    # an upper-body crop
//
// Writes assets/hero/<variant>-<width>.webp and lib/hero-photo.generated.ts (static imports, so
// Next serves them hashed and immutable from /_next/static/media).
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import sharp from 'sharp';

const SOURCES = {
  plain: 'public/images/profile/dleer-shinjuku.webp',
  detection: 'public/images/profile/dleer-shinjuku-RF-DETR.webp',
};

// A 3:4 window into the photo: `zoom` 1 is the whole frame; `x` centers it horizontally (0 to 1),
// `top` places its top edge, both as fractions of the photo
const CROPS = {
  full: { zoom: 1, x: 0.5, top: 0 },
  upper: { zoom: 1.8, x: 0.5, top: 0.167 },
};

const WIDTHS = [260, 390, 520];

const cropName = process.argv[2] || 'full';
const crop = CROPS[cropName];
if (!crop) throw new Error(`unknown crop '${cropName}' (${Object.keys(CROPS).join(', ')})`);

const root = process.cwd();
const out = join(root, 'assets/hero');
await mkdir(out, { recursive: true });
for (const file of await readdir(out)) await rm(join(out, file));

const imports = [];
const lists = {};
for (const [variant, path] of Object.entries(SOURCES)) {
  const source = sharp(join(root, path));
  const { width: W, height: H } = await source.metadata();
  // The largest 3:4 window that fits the photo, shrunk by the zoom
  const w = Math.round(Math.min(W, (H * 3) / 4) / crop.zoom);
  const h = Math.round((w * 4) / 3);
  const left = Math.round(Math.min(W - w, Math.max(0, crop.x * W - w / 2)));
  const top = Math.round(Math.min(H - h, Math.max(0, crop.top * H)));
  lists[variant] = [];
  for (const width of WIDTHS) {
    const name = `${variant}-${width}`;
    const info = await sharp(join(root, path))
      .extract({ left, top, width: w, height: h })
      .resize({ width })
      .webp({ quality: 74, effort: 6 })
      .toFile(join(out, `${name}.webp`));
    imports.push(`import ${variant}_${width} from '@/assets/hero/${name}.webp';`);
    lists[variant].push(`${variant}_${width}`);
    console.log(`${name}.webp ${info.width}x${info.height} ${(info.size / 1024).toFixed(1)} KB`);
  }
}

const source = `// Generated by scripts/build-hero-photo.mjs (crop: ${cropName}). Do not edit; rerun the script instead.
import type { StaticImageData } from 'next/image';
${imports.join('\n')}

/** The neofetch tile's photo (3:4), ${WIDTHS.join(', ')} px wide, plain and with RF-DETR's detections. */
export const HERO_PHOTO: Record<'plain' | 'detection', StaticImageData[]> = {
  plain: [${lists.plain.join(', ')}],
  detection: [${lists.detection.join(', ')}],
};
`;
await writeFile(join(root, 'lib/hero-photo.generated.ts'), source);
console.log(`wrote lib/hero-photo.generated.ts (crop: ${cropName})`);
