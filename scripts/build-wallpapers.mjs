// Pre-blurs the wallpapers (docs/PORTFOLIO_V2_SPEC.md, phase 1, P2 and P5).
//
// The wallpaper always renders blurred behind the tiles. Blurring a full-screen 1920 px image with
// CSS `filter: blur()` costs the browser on every repaint, and the 1920 px file costs 160 KB to
// download. Blurred content has no fine detail, so a 640 px pre-blurred copy, scaled up, looks the
// same and weighs a few KB. Run this after adding or changing a wallpaper in public/images, then
// commit the outputs:
//
//   node scripts/build-wallpapers.mjs
//
// Writes assets/wallpapers/<name>.webp and lib/wallpapers.generated.ts (static imports, so Next
// serves them hashed and immutable from /_next/static/media, with a blur placeholder each).
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import sharp from 'sharp';

// Must match themeBackgrounds in contexts/ThemeContext.tsx (tests/wallpapers.test.ts checks it).
// `blur` is the preset's CSS blur in px, from the old filter in components/layout/Background.tsx.
const WALLPAPERS = {
  'tokyo-night': { blur: 8, names: ['purple-girl', 'cat_anime-girl', 'shiny_purple', 'pixel_big_city'] },
  nord: { blur: 6, names: ['cool_rocks', 'lets_go_home', 'gradient-pb'] },
  'solarized-light': { blur: 4, names: ['pastel-window', 'yellow_kyoto', 'ign_colorful'] },
};

const WIDTH = 640;
// A wallpaper covering a 1920 px desktop, or a phone's full height, renders about 1,600 CSS px
// wide; scale the CSS blur radius to the 640 px copy accordingly
const REFERENCE_WIDTH = 1600;

const root = process.cwd();
const out = join(root, 'assets/wallpapers');
await mkdir(out, { recursive: true });

const entries = [];
for (const { blur, names } of Object.values(WALLPAPERS)) {
  for (const name of names) {
    const sigma = (blur * WIDTH) / REFERENCE_WIDTH;
    const info = await sharp(join(root, 'public/images', `${name}.webp`))
      .resize({ width: WIDTH, withoutEnlargement: true })
      .blur(sigma)
      .webp({ quality: 70, effort: 6 })
      .toFile(join(out, `${name}.webp`));
    entries.push({ name, ident: name.replace(/[^a-zA-Z0-9]/g, '_'), size: info.size });
    console.log(`${name}.webp ${info.width}x${info.height} ${(info.size / 1024).toFixed(1)} KB (sigma ${sigma.toFixed(1)})`);
  }
}

const source = `// Generated by scripts/build-wallpapers.mjs. Do not edit; rerun the script instead.
import type { StaticImageData } from 'next/image';
${entries.map((e) => `import ${e.ident} from '@/assets/wallpapers/${e.name}.webp';`).join('\n')}

/** Pre-blurred wallpapers by file name (no extension), e.g. 'purple-girl'. */
export const BLURRED_WALLPAPERS: Record<string, StaticImageData> = {
${entries.map((e) => `  '${e.name}': ${e.ident},`).join('\n')}
};
`;
await writeFile(join(root, 'lib/wallpapers.generated.ts'), source);
console.log('wrote lib/wallpapers.generated.ts');
